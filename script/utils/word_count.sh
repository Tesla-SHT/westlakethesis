#/bin/bash

if ! [ -f out/westlakethesis.fls ]; then
    echo "Cannot find file 'out/westlakethesis.fls', which is generated by latexmk"
    echo "Please use 'latexmk' command to compile westlakethesis first, then run"
    echo "this script under the project root dir to count words"
    exit 1
fi

cat out/westlakethesis.fls            \
    | uniq                            \
    | grep body                       \
    | grep .tex                       \
    | grep -v thanksto.tex            \
    | grep -v acknowledgement.tex     \
    | grep -v review.tex              \
    | grep -v original.tex            \
    | grep -v cv.tex                  \
    | cut -d ' ' -f 2                 \
    | awk '{ print "\\input{"$1"}" }' \
    > out/westlakethesis.wordcnt      \
;

texcount out/westlakethesis.wordcnt -inc
